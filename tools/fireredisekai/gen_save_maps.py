#!/usr/bin/env python3
"""Regenerate src/data/fireredisekai_save_maps.h: the buildings that autosave on entry.
Run from the repo root."""
import json, os, re
names = [d for d in sorted(os.listdir('data/maps')) if d.endswith('_Frlg')]
pat = re.compile(r'(PokemonCenter_1F|_Gym$|_Mart$|DepartmentStore_1F|ProfessorOaksLab|PlayersHouse_1F|PlayersHouse_2F|RivalsHouse|Museum_1F)')
ids = [json.load(open(f'data/maps/{d}/map.json'))['id'] for d in names if pat.search(d[:-5])]
out = ('// FireRed Isekai: buildings that autosave on entry (generated by tools/fireredisekai/gen_save_maps.py).\n'
       '// Centers, gyms, Marts and story places.\nstatic const u16 sIsekaiSaveMaps[] =\n{\n'
       + ''.join(f'    {i},\n' for i in ids) + '};\n')
open('src/data/fireredisekai_save_maps.h', 'w').write(out)
print(len(ids), 'maps')
